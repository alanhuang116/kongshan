/**
 * 村里各人自己的话。都是本应用自撰的家常话，不是古书里的：界面上不配书名号，不署古人的名。
 * 名册（谁、叫什么、家里有谁、每天几点在哪做什么）在 src/data/folk.ts（村人那一路写）；这里只管各人怎么说话：
 *
 *   greet 招呼（看时辰、天气、情分）· again 一天里又见着 · long 隔了好些日子才见
 *   busy  问他在忙什么：按此刻做的那件事（名册 plan 里的 act）答；'*' 是别的时候 · busyQ 那时先生怎么问（签上的字）
 *   ask   问农事、问手艺、问路：q 先生问的那句，a 他答的几句（一回说一句），more 是「再问一句」的签
 *         special：almanac 节气农事（almanac.ts）· yuqiao 渔樵问对（talk.ts 的 YUQIAO，原文）· verse 童子背那首数数的歌
 *   home  闲话家常：家里的人和事、邻里（homeQ 是先生问的那句）
 *   idle  闲话 · like / ok / no 收到合心意的、平常的、不肯收的东西 · got 收到某一样东西时专门的话
 *   back  回赠时说的 · treat 见面塞东西时说的（{物} 是那样东西）· bye 告辞
 *   calls 熟到各档（初识、相熟、相得、知交）时怎么叫先生（不给就用名册里的 call）
 *   favorHint 有事求你、自己先开口的一句 · giftAsk 先生说「带了样东西」时他说的 · after 先生「先不了」之后他说的
 *
 * 每一句可带一个 O：
 *   when 只在这些时令、时辰、天气说（spring summer autumn winter · dawn am noon pm dusk night day · rain snow fair mist，或节气名），写几个就是合其中一个即可；
 *   bond 情分到了几档才说（1 初识 2 相熟 3 相得 4 知交）；fam 说到的这几个人得是他家里人；about 说到的这几个人得在名册里；
 *   act 他此刻在做这几件事时才说；back 他回问先生一句：[先生答的（签上的字）, 他再接的]。
 * 话里的「{某人的 id}」显示时换成那人的名字（名册里的 name），「{先生}」换成他此刻怎么叫你。
 * 不占卜、不断吉凶：有人问年景，先生只答「春种秋收，便是大吉」。话短、口气各不相同，不说教。
 */
